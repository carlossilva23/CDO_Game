// This is how to intialize variables of different types 
//
// Always start with "let", this tells the computer that this is the beginning of a variable declaration 

// let 

// Next comes the name of your variable plus and equal sign 

// let ____ =

// Then you simply fill in your variable and add a semi-colon to the end of the statement

// Integer
let number = 23;

// Float
let decimal = 42.7;

// String
let name = 'Carlos';

// Boolean
let decision = true;

