// A while loop repeats a block of code as long as a condition is true. 
// Before each repetition, it checks the condition again, and once that condition becomes false, the loop stops.

start = 0;
while (start < 5) {
    start ++;
    console.log(start);
}

// Notice how there wasn't a need to re run the program everytime you wanted to see the value of start.
